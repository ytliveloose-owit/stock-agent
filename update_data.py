from datetime import datetime
import calendar
import os

import pandas as pd
import jquantsapi


# ==========================================================
# J-Quants
# ==========================================================

cli = jquantsapi.ClientV2()


# ==========================================================
# 取得したい年月
# ここだけ変更
# ==========================================================

YEAR = 2023
MONTH = 4


# ==========================================================
# 取得期間
# ==========================================================

start_dt = datetime(
    YEAR,
    MONTH,
    1
)

last_day = calendar.monthrange(
    YEAR,
    MONTH
)[1]

end_dt = datetime(
    YEAR,
    MONTH,
    last_day
)


print()
print("==========================")
print("取得期間")
print("==========================")

print(
    f"{start_dt.date()} ～ {end_dt.date()}"
)


# ==========================================================
# 日足データ取得
# ==========================================================

print()
print("J-Quantsから株価データを取得中...")


df = cli.get_eq_bars_daily_range(
    start_dt=start_dt,
    end_dt=end_dt
)


print(
    f"取得件数：{len(df):,}件"
)


# ==========================================================
# 必要列のみ残す
# ==========================================================

df = df[
    [
        "Date",
        "Code",
        "AdjO",
        "AdjH",
        "AdjL",
        "AdjC",
        "AdjVo",
    ]
].copy()


# ==========================================================
# Codeを文字列として統一
# ==========================================================

df["Code"] = df["Code"].astype(str)


# ==========================================================
# Date型統一
# ==========================================================

df["Date"] = pd.to_datetime(
    df["Date"],
    format="mixed"
)


# ==========================================================
# 東証プライム銘柄のみ
# ==========================================================

print()
print("東証プライム銘柄を抽出中...")


master = cli.get_eq_master()


prime = master[
    master["MktNm"] == "プライム"
][
    ["Code"]
].copy()


prime["Code"] = prime["Code"].astype(str)


df = df.merge(
    prime,
    on="Code",
    how="inner"
)


print(
    f"プライム抽出後：{len(df):,}件"
)


# ==========================================================
# 年ごとのCSVファイル
# ==========================================================

csv_file = f"daily_data_{YEAR}.csv"


# ==========================================================
# 既存CSVの読み込み
# ==========================================================

if os.path.exists(csv_file):

    print()
    print("==========================")
    print("既存CSV")
    print("==========================")

    print(
        f"既存ファイル：{csv_file}"
    )


    old = pd.read_csv(
        csv_file,
        dtype={
            "Code": str
        }
    )


    old["Code"] = old["Code"].astype(str)


    old["Date"] = pd.to_datetime(
        old["Date"],
        format="mixed"
    )


    print(
        f"既存件数：{len(old):,}件"
    )


else:

    print()
    print("==========================")
    print("新規CSV")
    print("==========================")

    print(
        f"{csv_file} は存在しません。"
    )


    old = pd.DataFrame()


# ==========================================================
# 新規データと既存データを結合
# ==========================================================

if not old.empty:

    df = pd.concat(
        [
            old,
            df
        ],
        ignore_index=True
    )


# ==========================================================
# Code + Dateで重複削除
# ==========================================================

before = len(df)


df = (
    df
    .drop_duplicates(
        subset=[
            "Code",
            "Date"
        ],
        keep="last"
    )
    .sort_values(
        [
            "Code",
            "Date"
        ]
    )
    .reset_index(drop=True)
)


after = len(df)


print()
print("==========================")
print("重複処理")
print("==========================")

print(
    f"重複削除：{before - after:,}件"
)


# ==========================================================
# CSV保存
# ==========================================================

df.to_csv(
    csv_file,
    index=False,
    encoding="utf-8-sig"
)


# ==========================================================
# 保存結果
# ==========================================================

file_size_mb = (
    os.path.getsize(csv_file)
    / 1024
    / 1024
)


print()
print("==========================")
print("保存完了")
print("==========================")


print(
    f"ファイル：{csv_file}"
)


print(
    f"保存先：{os.path.abspath(csv_file)}"
)


print(
    f"保存件数：{len(df):,}件"
)


print(
    f"ファイルサイズ：{file_size_mb:.2f} MB"
)


# ==========================================================
# データ確認
# ==========================================================

print()
print("==========================")
print("データ確認")
print("==========================")


print(
    df.head()
)


print()
print("==========================")
print("処理終了")
print("==========================")
